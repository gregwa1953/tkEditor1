    ed2 = tkEditor1.CodeEditor(_w1.frameEd2)
    # Set the title of the Toplevel
    _top1.title(f"{programName} - {version}")

    # Get the version of the editor code and the licence
    libVer = ed1.get_version()
    libLic = ed1.get_licence()
