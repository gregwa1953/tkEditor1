def on_btnFileOpen(*args):
    if _debug:
        print("tkEditorDemo1_support.on_btnFileOpen")
        for arg in args:
            print("    another arg:", arg)
        sys.stdout.flush()
    global ed1, ed2, current_filename, basefile, currenttab
    if currenttab == 0:
        editorToUse = ed1
    elif currenttab == 1:
        editorToUse = ed2
    # editorToUse = f"ed{currenttab+1}"
    # print(f"{editorToUse}")
    # editorObject = object(editorToUse)
    basefile = ""
    if _debug:
        print("pyed2a_support.on_btnFileOpen")
        for arg in args:
            print("    another arg:", arg)
        sys.stdout.flush()
    filename = askopenfilename(
        initialdir=location,
        title="Select A File",
        parent=_top1,
        filetypes=(
            ("Python files", "*.py"),
            ("ttd files", "*.ttd"),
            ("Markdown", "*.md"),
            ("RST files", "*.rst"),
            ("text files", "*.txt"),
            ("Any Files", "*.*"),
        ),
    )
    # print(filename)
    if filename != ():
        if filename != "":
            if _debug:
                print(f"{filename}")
            # return filename
            editorToUse.clear_editor()
            editorToUse.load_file(filename)
            current_filename = filename
            basefile = os.path.basename(current_filename)
    _top1.title(f"{programName} - {version} - {basefile}")
    _w1.TNotebook1.tab(currenttab, text=basefile)

def on_btnFileSave(*args):
    if _debug:
        print("tkEditorDemo1_support.on_btnFileSave")
        for arg in args:
            print("    another arg:", arg)
        sys.stdout.flush()
    global current_filename, basefile

    contents = ed1.text.get(1.0, END)
    if current_filename == "":
        # ask filename and location
        file_path = asksaveasfilename(
            defaultextension=".txt",
            filetypes=[
                ("Python files", "*.py"),
                ("ttd files", "*.ttd"),
                ("Markdown", "*.md"),
                ("RST files", "*.rst"),
                ("text files", "*.txt"),
                ("Any Files", "*.*"),
            ],
            initialdir=location,  # Optional: set initial directory
            title="Save your file",  # Optional: set dialog title
        )
        if file_path:
            # User selected a file path, now you can write data to it
            with open(file_path, "w") as f:
                f.write(contents)
            if _debug:
                print(f"File saved to: {file_path}")
            basefile = os.path.basename(file_path)
            _top1.title(f"{programName} - {version} - {basefile} - Saved")
            _w1.TNotebook1.tab(0, text=basefile)

        else:
            print("Save operation cancelled.")
    else:
        with open(current_filename, "w") as f:
            f.write(contents)
        if _debug:
            print(f"File Write complete")
    _top1.title(f"{programName} - {version} - {basefile} - Saved")
    _w1.TNotebook1.tab(0, text=basefile)

def write_file(filename, strng):
    with open(filename, "w") as f:
        f.write(strng)

def read_file(filename):
    # ======================================================
    # function read_file()
    # ======================================================
    # Read file, leaving end of lines
    # ======================================================
    with open(filename) as f:
        lines = f.read()
    return lines

