    def_editor_bg_color = "white"
    def_keyword_color = "#0000ff"
    def_string_color = "#a31515"
    def_comment_color = "#008000"
    def_current_line_bg_color = "#f0f8ff"
    def_current_Editor_bg_color = "white"
